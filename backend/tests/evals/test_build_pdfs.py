# tests/evals/test_build_pdfs.py

# --- Python Standard Library ---
from pathlib import Path
from typing import Final

# --- Third Party Libraries ---
import pytest

# --- App modules ---
from aie_estimator.foundation.attachments.extractor import extract_text
from evals.stress.fixtures.build_pdfs import (
    STRESS_PDF_SIZES_KB,
    build_calibrated_pdf,
    canary_facts,
    generate_corpus,
)

_BYTES_PER_KB: Final[int] = 1024
_CALIBRATION_TOLERANCE: Final[float] = 0.10
_DEFAULT_MAX_CHARS: Final[int] = 60_000


@pytest.mark.parametrize("size_kb", STRESS_PDF_SIZES_KB)
def test_build_calibrated_pdf_is_deterministic_and_calibrated(size_kb: int) -> None:
    """
    GIVEN a target stress PDF size in kilobytes
    WHEN build_calibrated_pdf is invoked twice
    THEN identical bytes are produced within 10% of the target byte size.

    :param size_kb: Target PDF size in kilobytes.
    """
    first = build_calibrated_pdf(size_kb)
    second = build_calibrated_pdf(size_kb)

    assert first == second
    target_bytes = size_kb * _BYTES_PER_KB
    assert abs(len(first) - target_bytes) <= target_bytes * _CALIBRATION_TOLERANCE


@pytest.mark.parametrize("size_kb", STRESS_PDF_SIZES_KB)
def test_generated_pdf_round_trips_and_respects_canary_budget(size_kb: int) -> None:
    """
    GIVEN a calibrated stress PDF generated by build_calibrated_pdf
    WHEN extract_text parses it under the default 60_000-character budget
    THEN extraction succeeds, start canary survives, and 100 KB truncates the end canary.

    :param size_kb: Target PDF size in kilobytes.
    """
    payload = build_calibrated_pdf(size_kb)
    extracted, truncated_chars = extract_text(
        filename=f"attach_{size_kb}kb.pdf",
        content=payload,
        max_chars=_DEFAULT_MAX_CHARS,
    )
    start_fact, mid_fact, end_fact = canary_facts(size_kb)

    assert start_fact in extracted
    if size_kb <= 50:
        assert mid_fact in extracted
        assert end_fact in extracted
        assert "[... truncated ...]" not in extracted
        assert truncated_chars == 0
    else:
        assert "[... truncated ...]" in extracted
        assert end_fact not in extracted
        assert truncated_chars > 0


def test_generate_corpus_writes_expected_files(tmp_path: Path) -> None:
    """
    GIVEN a temporary output directory
    WHEN generate_corpus executes
    THEN all four calibrated attach_<size>kb.pdf files are written and non-empty.

    :param tmp_path: Temporary directory provided by pytest.
    """
    generated = generate_corpus(output_dir=tmp_path)

    assert tuple(generated.keys()) == STRESS_PDF_SIZES_KB
    for size_kb, pdf_path in generated.items():
        assert pdf_path.name == f"attach_{size_kb}kb.pdf"
        assert pdf_path.exists()
        assert pdf_path.stat().st_size > 0


def test_build_calibrated_pdf_rejects_non_positive_size() -> None:
    """
    GIVEN a non-positive size_kb argument
    WHEN build_calibrated_pdf is called
    THEN a ValueError is raised.
    """
    with pytest.raises(ValueError, match=r"must be positive"):
        build_calibrated_pdf(0)
